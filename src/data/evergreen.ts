export const EVERGREEN_POOL: Record<string, BriefingCategory[]> = {
  economy: [economySet1, economySet2, economySet3],
  investment: [investmentSet1, investmentSet2, investmentSet3],
  lifestyle: [lifestyleSet1, lifestyleSet2, lifestyleSet3],
};

/**
 * 날짜 기반으로 에버그린 콘텐츠 선택
 * 같은 날짜에는 항상 같은 세트가 선택됨 (결정적 알고리즘)
 */
export function getEvergreenBriefing(
  category: string,
  date: string,
): BriefingCategory | null {
  const pool = EVERGREEN_POOL[category];
  if (!pool || pool.length === 0) return null;

  const index = parseInt(date.replace(/-/g, ''), 10) % pool.length;
  return pool[index];
}
